import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, writeFile, copyFile, mkdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { gzipSync } from "node:zlib";

const root = resolve(import.meta.dir, "renderer");
const generated = join(import.meta.dir, "generated");
await mkdir(generated, { recursive: true });
const temporary = await mkdtemp(join(tmpdir(), "lenso-glass-renderer-"));
try {
  execFileSync(
    process.env["LENSO_CARGO"] ?? "cargo",
    [
      "build",
      "--manifest-path",
      join(root, "Cargo.toml"),
      "--release",
      "--target",
      "wasm32-unknown-unknown",
      "--locked",
      "--offline",
    ],
    { stdio: "inherit", env: { ...process.env, CARGO_TARGET_DIR: join(temporary, "target") } },
  );
  execFileSync(
    "wasm-bindgen",
    [
      join(temporary, "target/wasm32-unknown-unknown/release/lenso_glass_renderer.wasm"),
      "--target",
      "web",
      "--out-dir",
      temporary,
      "--out-name",
      "runtime",
      "--remove-name-section",
      "--remove-producers-section",
    ],
    { stdio: "inherit" },
  );
  const binary = await readFile(join(temporary, "runtime_bg.wasm"));
  const gzipBytes = gzipSync(binary).length;
  if (binary.length > 48 * 1024 || gzipBytes > 20 * 1024)
    throw new Error(
      `Renderer exceeds its 48 KiB raw / 20 KiB gzip budget: ${binary.length} / ${gzipBytes}`,
    );
  await copyFile(join(temporary, "runtime.d.ts"), join(generated, "runtime.d.ts"));
  await writeFile(
    join(generated, "runtime.js"),
    "/* oxlint-disable no-unused-vars -- Generated by wasm-bindgen. */\n" +
      (await readFile(join(temporary, "runtime.js"), "utf8")),
  );
  const sourceFiles = [
    "Cargo.toml",
    "Cargo.lock",
    "src/lib.rs",
    "src/web.rs",
    "../../../packages/glass/shaders/ios27.frag",
    "../../../packages/glass/shaders/quad.vert",
    "../../../packages/glass/shaders/blur.frag",
  ];
  const digest = createHash("sha256");
  for (const file of sourceFiles) digest.update(await readFile(join(root, file)));
  const sourceHash = digest.digest("hex");
  await writeFile(
    join(generated, "binary.ts"),
    `// Generated by experiments/glass-driver-comparison/build-wasm.ts; do not edit.\nexport const sourceHash = "${sourceHash}";\nexport const binary = ${JSON.stringify(binary.toString("base64"))};\n`,
  );
  console.log(`Renderer Wasm: ${binary.length} bytes raw, ${gzipBytes} bytes gzip`);
} finally {
  await rm(temporary, { recursive: true, force: true });
}
