const declarations = (values: Record<string, string>) =>
  Object.entries(values)
    .map(([name, value]) => `  --lenso-${name}: ${value};`)
    .join("\n");
const selectors = (dark: boolean) =>
  dark
    ? '.dark, [data-theme="dark"], :host(.dark), :host([data-theme="dark"])'
    : ':root, :host, .light, .default, [data-theme="light"], [data-theme="default"], :host(.light), :host([data-theme="light"])';
const scoped = (selector: string, attr: string) =>
  selector
    .split(", ")
    .map((s) =>
      s.startsWith(":host")
        ? s.replace(/\)$/, `${attr})`) === s
          ? `:host(${attr})`
          : s.replace(/\)$/, `${attr})`)
        : s + attr,
    )
    .join(", ");
