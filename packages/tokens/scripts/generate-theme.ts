      const high = phase === "media" || phase === "increased";
      const env =
        `${dark ? "dark" : "light"}-${high ? "increased" : "standard"}-${elevated ? "elevated" : "base"}` as ColorEnvironment;
      const attrs = `${phase === "standard" || phase === "increased" ? `[data-contrast="${phase}"]` : ""}${elevated ? '[data-level="elevated"]' : ""}`;
