export function getDocumentationMessages(language: string) {
  return language === "cn" || /^zh(?:-|$)/iu.test(language) ? zh : en;
}

export function resolveDocumentationLocale(
  code: string,
  locales: readonly DocumentationLocale[] = [],
): DocumentationLocale {
  return (
    locales.find((locale) => locale.code === code) ?? {
      code,
      label: code,
      language: code === "cn" ? "zh-CN" : code,
    }
  );
}
