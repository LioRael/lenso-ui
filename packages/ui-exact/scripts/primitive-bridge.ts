export function disclosureBridge(source: string, license: string) {
  const shapes = [
    declaration(source, "shape", "DisclosureState"),
    declaration(source, "shape", "AccordionState") +
      "\n  orientation: string\n  loopFocus: bool\n  variant: string\n  hideSeparator: bool",
    declaration(source, "shape", "AccordionItemState"),
  ].join("\n\n");
  const specs = [
    {
      name: "Disclosure",
      native: "    column id=state.id testId=state.id",
      attrs: 'hatch="lenso-ui" data-lenso-kind="disclosure" data-slot="disclosure"',
    },
    {
      name: "DisclosureTrigger",
      native:
        "    button id=`${state.id}-trigger` testId=`${state.id}-trigger` aria-label=label\n      aria-expanded=state.open aria-controls=`${state.id}-panel` disabled=state.disabled\n      press=change(not state.open)",
      attrs:
        'appearance="none" tabindex=0 hatch="lenso-ui" data-lenso-kind="disclosure-trigger" data-slot="disclosure-trigger" data-lenso-panel-open=state.open',
    },
    {
      name: "Accordion",
      native: "    column id=state.id testId=state.id",
      attrs:
        'hatch="lenso-ui" data-lenso-kind="accordion" data-slot="accordion" data-orientation=state.orientation data-lenso-loop-focus=state.loopFocus data-lenso-variant=state.variant',
    },
    {
      name: "AccordionItem",
      native: "    column id=item.id testId=item.id",
      attrs:
        'hatch="lenso-ui" data-lenso-kind="accordion-item" data-slot="accordion-item" data-lenso-hide-separator=state.hideSeparator',
      props: "    state: AccordionState\n",
    },
    {
      name: "AccordionTrigger",
      native:
        "    button id=`${item.id}-trigger` testId=`${item.id}-trigger` aria-label=label\n      aria-expanded=expanded aria-controls=`${item.id}-panel` disabled=(state.disabled or item.disabled) press=toggle",
      attrs:
        'appearance="none" tabindex=0 hatch="lenso-ui" data-lenso-kind="accordion-trigger" data-slot="accordion-trigger" data-lenso-panel-open=expanded data-lenso-variant=state.variant',
    },
  ];
  const generated = specs.map((spec) => {
    let result = bridge(
      source,
      license,
      spec.name,
      spec.native,
      spec.attrs,
      spec.props ?? "",
      "components/disclosure.contract",
    ).contract;
    if (spec.name.endsWith("Trigger"))
      result = result
        .replace("    label: string\n", "")
        .replace(" aria-label=label", "")
        .replaceAll("-panel`", "-content`");
    return result;
  });
  return {
    sourceSHA256: createHash("sha256").update(source).digest("hex"),
    contract: shapes + "\n\n" + generated.join("\n"),
  };
}
