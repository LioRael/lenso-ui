export function menuPartsBridge(source: string, license: string) {
  const root = bridge(
    source,
    license,
    "Menu",
    '    column id=id testId=id popover="auto" role="menu" aria-label=label',
    'tabindex=-1 aria-labelledby=labelledBy hatch="lenso-ui" data-lenso-kind="menu-positioner" data-slot="menu-positioner" data-lenso-modal=modal data-lenso-side=side data-lenso-align=align data-lenso-direction=direction data-lenso-side-offset=sideOffset data-lenso-align-offset=alignOffset data-lenso-collision-padding=collisionPadding data-lenso-collision-avoidance=collisionAvoidance data-lenso-disable-anchor-tracking=disableAnchorTracking',
    "    labelledBy: string\n    modal: bool\n    side: string\n    align: string\n    direction: string\n    sideOffset: number\n    alignOffset: number\n    collisionPadding: number\n    collisionAvoidance: bool\n    disableAnchorTracking: bool\n",
    "components/popover.contract",
  );
  root.contract = root.contract
    .replace("component StyledMenu", "component StyledMenuPositioner")
    .replace("    column id=id", "    box id=id");
  const trigger = bridge(
    source,
    license,
    "PopoverTrigger",
    "    button id=id testId=id aria-label=label popovertarget=target disabled=disabled",
    'appearance="none" tabindex=0 aria-haspopup="menu" popovertargetaction="toggle" hatch="lenso-ui" data-lenso-kind="menu-trigger" data-slot="menu-trigger" data-lenso-icon-only=iconOnly',
    "    iconOnly: bool\n",
    "components/popover.contract",
  );
  trigger.contract = trigger.contract.replace(
    "component StyledPopoverTrigger",
    "component StyledMenuTrigger",
  );
  const items = ["MenuItem", "MenuAction", "MenuItemCheckbox", "MenuItemRadio"].map((name) => {
    const checked = name === "MenuItemCheckbox" || name === "MenuItemRadio";
    const kind = name === "MenuAction" ? "menu-action" : "menu-item";
    const result = bridge(
      source,
      license,
      "MenuItem",
      '    button id=id testId=id role="menuitem" aria-label=label disabled=disabled press=press\n      commandfor=target command="hide-popover"',
      `appearance="none" tabindex=-1 aria-disabled=disabled hatch="lenso-ui" data-lenso-kind="${kind}" data-slot="menu-item" data-lenso-variant=variant data-lenso-disabled=disabled data-lenso-close-on-click=closeOnClick${checked ? " aria-checked=checked" : ""}`,
      "    variant: string\n    closeOnClick: bool\n" + (checked ? "    checked: bool\n" : ""),
      "components/popover.contract",
    );
    result.contract = result.contract
      .replace("component StyledMenuItem", `component Styled${name}`)
      .replace(
        'commandfor=target command="hide-popover"',
        'popovertarget=(closeOnClick ? target : "") popovertargetaction="hide"',
      );
    if (checked)
      result.contract = result.contract.replace(
        'role="menuitem"',
        name === "MenuItemCheckbox" ? 'role="menuitemcheckbox"' : 'role="menuitemradio"',
      );
    return result.contract;
  });
  const submenu = bridge(
    source,
    license,
    "MenuSubmenuTrigger",
    '    button id=id testId=id role="menuitem" aria-label=label popovertarget=target disabled=disabled',
    'appearance="none" tabindex=-1 aria-haspopup="menu" aria-disabled=disabled popovertargetaction="toggle" hatch="lenso-ui" data-lenso-kind="menu-submenu-trigger" data-slot="menu-submenu-trigger" data-lenso-for=target data-lenso-disabled=disabled data-lenso-open-on-hover=openOnHover data-lenso-hover-delay=delay data-lenso-close-delay=closeDelay data-lenso-close-on-click="false"',
    "    openOnHover: string\n    delay: number\n    closeDelay: number\n",
    "components/popover.contract",
  );
  return {
    sourceSHA256: root.sourceSHA256,
    contract: [root.contract, trigger.contract, ...items, submenu.contract].join("\n"),
  };
}
