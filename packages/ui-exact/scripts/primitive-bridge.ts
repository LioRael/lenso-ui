import { createHash } from "node:crypto";
import { mkdir } from "node:fs/promises";
import path from "node:path";

function declaration(source: string, kind: string, name: string) {
  const lines = source.split("\n");
  const start = lines.indexOf(`${kind} ${name}`);
  if (start < 0) throw new Error(`Missing canonical ${name}`);
  let end = start + 1;
  while (end < lines.length && (!lines[end]!.trim() || /^\s/.test(lines[end]!))) end++;
  return lines.slice(start, end).join("\n").trimEnd();
}
function bridge(
  source: string,
  license: string,
  component: string,
  native: string,
  attributes: string,
  props = "",
  sourcePath = "components/field.contract",
) {
  const block = declaration(source, "component", component);
  if (block.split(native).length !== 2 || /\bhatch=/.test(block))
    throw new Error(`${component} anatomy changed; review the styling bridge`);
  const hash = createHash("sha256").update(source).digest("hex");
  return {
    sourceSHA256: hash,
    contract: [
      "// Generated by scripts/primitive-bridge.ts. Do not edit.",
      `// Source: @lenso/primitives-exact/${sourcePath}`,
      `// Source SHA256: ${hash}`,
      ...license
        .trimEnd()
        .split("\n")
        .map((line) => `// ${line}`),
      "",
      block
        .replace(`component ${component}`, `component Styled${component}`)
        .replace(/(?=^  (?:derive|action|slot|view)\b)/m, props)
        .replace(native, `${native} ${attributes}`),
      "",
    ].join("\n"),
  };
}
export function descriptionBridge(source: string, license: string) {
  return bridge(
    source,
    license,
    "FieldDescription",
    "    text message id=id testId=id",
    'hatch="lenso-ui" data-lenso-kind="description" data-slot="description"',
  );
}
export function inputBridge(source: string, license: string) {
  const mode =
    '(type == "password" ? "password" : type == "search" ? "search" : type == "email" ? "email" : type == "url" ? "url" : type == "tel" ? "tel" : "text")';
  const native = `    input id=id testId=id aria-label=label aria-describedby=description aria-invalid=invalid\n      value=value type=${mode}\n      placeholder=placeholder disabled=disabled readonly=readOnly\n      input=input change=change submit=submit`;
  const generated = bridge(
    source,
    license,
    "Input",
    native,
    'data-lenso-name=name aria-labelledby=labelledBy autocomplete=autocomplete data-lenso-required=required aria-required=required hatch="lenso-ui" data-lenso-kind="input" data-lenso-variant=variant data-lenso-invalid=invalid',
    "    name: string\n    labelledBy: string\n    autocomplete: string\n    required: bool\n    variant: string\n",
  );
  const typeContract = '    type: enum<"text", "search", "email", "url", "tel", "password">';
  if (!generated.contract.includes(typeContract))
    throw new Error("Input type contract changed; review the UI projection");
  // The canonical mapping is identity on its six declared modes. Preserve the UI's broader static type API on one node.
  return {
    ...generated,
    contract: generated.contract
      .replace(typeContract, "    type: string")
      .replace(`type=${mode}`, "type=type"),
  };
}
