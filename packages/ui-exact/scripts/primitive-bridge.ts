    source,
    license,
    "TabsList",
    native,
    'aria-disabled=disabled hatch="lenso-ui" data-lenso-kind="tabs-list" data-slot="tabs-list" data-orientation=orientation data-lenso-direction=direction data-lenso-size=size data-lenso-elastic=elastic data-lenso-glass=glass data-lenso-lift=lift data-lenso-disabled=disabled data-lenso-activate-on-focus=activateOnFocus data-lenso-loop-focus=loopFocus',
